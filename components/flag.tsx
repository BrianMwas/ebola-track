/** Country flag by ISO 3166-1 alpha-3 code. Decorative: the name is always next to it. */
export function Flag({
  iso3,
  className,
}: {
  iso3: string | null | undefined
  className?: string
}) {
  const Svg = iso3 ? FLAGS[iso3.toUpperCase()] : undefined
  if (!Svg) return null
  return (
    <Svg
      aria-hidden
      className={cn(
        "inline-block h-[0.9em] w-auto shrink-0 rounded-[2px] shadow-[0_0_0_1px_rgb(0_0_0/0.12)]",
        className
      )}
    />
  )
}
